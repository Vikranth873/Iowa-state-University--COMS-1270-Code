# Lab 3  - This code contains the product of 2 numbers from the user input 
# which will give the result of distance. 

Speed = float(input("Please enter the value of Speed in meters per second: "))
Time = float(input("Please enter the value of Time in seconds: "))
Distance = Speed * Time
print(f"The result of {Speed} * {Time} = {Distance}")